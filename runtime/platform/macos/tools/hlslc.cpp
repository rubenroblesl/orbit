// Build-time HLSL compiler for the macOS build (the role fxc /Fh plays on Windows): compiles one
// entry point with the runtime's D3DCompile and writes the blob as a C array header.
//
// usage: nebula_hlslc <target> <entry> <variable> <input.hlsl> <output.h>

#include <windows.h>
#include <d3dcompiler.h>

#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>

int main(int argc, char** argv) {
    if (argc != 6) {
        std::fprintf(stderr, "usage: %s <target> <entry> <variable> <input.hlsl> <output.h>\n", argv[0]);
        return 2;
    }
    std::ifstream input(argv[4], std::ios::binary);
    if (!input) {
        std::fprintf(stderr, "cannot read %s\n", argv[4]);
        return 1;
    }
    std::ostringstream text;
    text << input.rdbuf();
    const std::string source = text.str();
    ID3DBlob* code = nullptr;
    ID3DBlob* errors = nullptr;
    const HRESULT hr = D3DCompile(source.data(), source.size(), argv[4], nullptr, D3D_COMPILE_STANDARD_FILE_INCLUDE,
        argv[2], argv[1], D3DCOMPILE_OPTIMIZATION_LEVEL3, 0, &code, &errors);
    if (errors != nullptr) {
        std::fprintf(stderr, "%s", static_cast<const char*>(errors->GetBufferPointer()));
        errors->Release();
    }
    if (FAILED(hr) || code == nullptr) {
        std::fprintf(stderr, "%s: compilation failed (0x%08x)\n", argv[4], static_cast<unsigned>(hr));
        return 1;
    }
    std::ofstream output(argv[5], std::ios::binary | std::ios::trunc);
    output << "// Generated by nebula_hlslc from " << argv[4] << "\n";
    output << "const unsigned char " << argv[3] << "[] = {";
    const auto* bytes = static_cast<const unsigned char*>(code->GetBufferPointer());
    for (SIZE_T i = 0; i < code->GetBufferSize(); ++i) {
        if (i % 16u == 0u) output << "\n    ";
        output << static_cast<unsigned>(bytes[i]) << ',';
    }
    output << "\n};\n";
    code->Release();
    return output.good() ? 0 : 1;
}
